export function getGroupIcon(groupName: string, size = 16) {
  const lower = groupName.toLowerCase();
  if (lower.includes("role")) return <IconShield size={size} />;
  if (lower.includes("account") || lower.includes("user")) return <IconUsers size={size} />;
  if (lower.includes("security") || lower.includes("audit")) return <IconShieldCheck size={size} />;
  if (lower.includes("finance") || lower.includes("account")) return <IconCalculator size={size} />;
  if (lower.includes("website") || lower.includes("content") || lower.includes("cms")) return <IconGlobe size={size} />;
  if (lower.includes("approval") || lower.includes("registration")) return <IconFileCheck size={size} />;
  if (lower.includes("member")) return <IconUsers size={size} />;
  if (lower.includes("volunteer")) return <IconHeart size={size} />;
  if (lower.includes("document") || lower.includes("file")) return <IconFileText size={size} />;
  if (lower.includes("communication") || lower.includes("notice")) return <IconBell size={size} />;
  if (lower.includes("support") || lower.includes("help")) return <IconHelpCircle size={size} />;
  if (lower.includes("setting") || lower.includes("platform")) return <IconSettings size={size} />;
  if (lower.includes("recovery") || lower.includes("backup")) return <IconDatabase size={size} />;
  return <IconKey size={size} />;
}
